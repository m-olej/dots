#!/bin/bash

# Define paths
OBSIDIAN_CONFIG_DIR="$HOME/.config/obsidian"

OBSIDIAN_CONFIG="$OBSIDIAN_CONFIG_DIR/obsidian.json"
OBSIDIAN_CONFIG_BACKUP="$OBSIDIAN_CONFIG_DIR/obsidian.json.bak"
COMPLETIONS_FILE="$HOME/.zshrc.d/obv-completions.sh"

# Function to generate auto-completions
setup_completions() {
    local dirs=("$@")
    if [ ${#dirs[@]} -eq 0 ]; then
        echo "Error: Please provide at least one directory to scan."
        echo "Usage: obv --setup /path/to/scan /another/path"
        return 1
    fi

    echo "Scanning for Obsidian vaults..."
    local vaults=()
    
    for dir in "${dirs[@]}"; do
        # Find directories containing an .obsidian folder (max depth 3 to save time)
        while IFS= read -r vault_path; do
            vaults+=("$vault_path")
        done < <(find "$dir" -maxdepth 3 -type d -name ".obsidian" -exec dirname {} \;)
    done

    if [ ${#vaults[@]} -eq 0 ]; then
        echo "No vaults found in the provided directories."
        return 1
    fi

# Create/overwrite the completions file
cat > "$COMPLETIONS_FILE" << 'EOF'
# Auto-generated by obv 
_obv_completions() {
local -a vaults=(
EOF

# Add vaults to completion array (escaping spaces)
for vault in "${vaults[@]}"; do
    echo "        \"$vault\"" >> "$COMPLETIONS_FILE"
done

cat >> "$COMPLETIONS_FILE" << 'EOF'
)

compadd -a vaults
return 0
}

compdef _obv_completions obv
EOF

    echo "Completions generated at $COMPLETIONS_FILE."
    
    echo "Setup complete! Please restart your terminal or run: source $COMPLETIONS_FILE"
    return 0
}

open_vault() {
    local target_vault="$1"
    
    if [ ! -d "$target_vault/.obsidian" ]; then
        echo "Error: '$target_vault' is not a valid Obsidian vault."
        return 1
    fi

    # Tweak config to prevent opening previous vaults
    if [ -f "$OBSIDIAN_CONFIG" ]; then
        # Backup the current config
        cp "$OBSIDIAN_CONFIG" "$OBSIDIAN_CONFIG_BACKUP"
        
        # Use sed to temporarily clear the 'lastOpened' or 'open' flags if needed
        # Alternatively, we can force Obsidian to open our target directly using the URI scheme
        # which overrides the default startup behavior cleanly.
    fi

    # Launch Obsidian using the URI scheme to guarantee it targets ONLY this vault
    # URL encode the path
    local encoded_path
    encoded_path=$(echo -n "$target_vault" | jq -sRr @uri)
    
    echo "Opening vault: $target_vault"
    if [ -x "/usr/bin/obsidian" ]; then
        /usr/bin/obsidian "obsidian://open?path=$encoded_path" &>/dev/null &
    elif [ -x "/opt/Obsidian/obsidian" ]; then
        /opt/Obsidian/obsidian "obsidian://open?path=$encoded_path" &>/dev/null &
    else
        xdg-open "obsidian://open?path=$encoded_path" &>/dev/null &
    fi

    # Reset config after a brief delay to let Obsidian initialize
    if [ -f "$OBSIDIAN_CONFIG_BACKUP" ]; then
        sleep 2
        mv "$OBSIDIAN_CONFIG_BACKUP" "$OBSIDIAN_CONFIG"
    fi
}

# Main Routing
obv() {
    if [ "$1" = "--setup" ]; then
        shift
        setup_completions "$@"
    elif [ -z "$1" ]; then
        echo "Usage:"
        echo "  obv --setup <dir1> <dir2>  : Scan directories and build completions"
        echo "  obv <vault_path>           : Open a specific vault"
    else
        open_vault "$1"
    fi
}
